/**
 * 泡芙的房间 —— 玩具球
 *
 * 珊瑚橘的彩色拼接毛线球：主球 + 一圈奶油色织带 + 4 块半球拼色 + 3 个小毛线疙瘩。
 * 所有装饰件的外接半径都收在 0.19 以内（整体不超过 d 0.38），底部不穿地板。
 */
import * as THREE from 'three';
import { Part, PAL } from './common.js';

export function build(def) {
  const p = new Part(def);

  // 主球：d 0.36，底面正好落在局部 y = -0.18（世界 y = 0）
  p.sph(0.36, 0, 0, 0, PAL.coral, { seg: 28, seg2: 20 });

  // 织带：横着绕一圈的浅色带，略微凸出球面一点
  p.cyl(0.372, 0.052, 0, 0, 0, PAL.cream, { seg: 40 });

  // 拼接色块：埋在球里的小球，只露出球面上一块圆饼
  //   球心到小球心 = 0.107，小球半径 0.08 → 最远点 0.187（≤ 0.19）
  p.sph(0.16, 0.059, 0.053, 0.072, PAL.blue);          // 右前上方
  p.sph(0.16, -0.066, 0.062, 0.057, PAL.blueLight);    // 左前上方
  p.sph(0.16, -0.091, 0.048, 0.030, PAL.cream);        // 左侧偏上
  p.sph(0.16, 0.032, 0.067, -0.077, PAL.blueLight);    // 右后上方

  // 毛线疙瘩：更小的球（d 0.04），凸出一点点做手工质感
  //   球心到小球心 = 0.165，小球半径 0.02 → 最远点 0.185
  p.sph(0.04, 0.091, -0.099, 0.096, PAL.sand);         // 右前下方
  p.sph(0.04, -0.129, -0.082, -0.063, PAL.blueLight);  // 左后下方
  p.sph(0.04, -0.016, -0.091, 0.137, PAL.blue);        // 正前下方

  return p.finish();
}
